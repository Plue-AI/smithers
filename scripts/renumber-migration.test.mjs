 for (const failure of ["missing origin", "shadow origin", "changed landed", "other reservation", "wrong sqlc", "invalid inventory", "generation failure", "unused conversion"]) {
  test(`${vcs}: ${failure} is refused`, () => {
   const dir = mkdtempSync(join(tmpdir(), "renumber-refusal-"))
   try {
    schemaFixture(dir); checkout(dir, vcs); pending(dir)
    if (failure === "missing origin" || failure === "shadow origin") ok(dir, "git", ["update-ref", "-d", "refs/remotes/origin/main"])
    if (failure === "shadow origin") ok(dir, "git", ["branch", "origin/main"])
    if (failure === "changed landed") writeFileSync(join(dir, "packages/backend/db/product/migrations/0001_base.sql"), "SELECT 1;\n")
    if (failure === "other reservation") writeFileSync(join(dir, path), "-- Ticket: T-FIX-02\nCREATE TABLE widget (id bigint);\n")
    if (failure === "invalid inventory") writeFileSync(join(dir, "packages/backend/db/product/migrations/0003_gap.sql"), "SELECT 1;")
    if (failure === "generation failure") writeFileSync(join(dir,path),"-- Ticket: T-FIX-01\nCREATE TABLE widget (id bigint PRIMARY KEY,);\n")
    if (failure === "unused conversion") writeFileSync(join(dir,"packages/backend/db/ownership.csv"),"table,target_owner,status\nbase,product,installed\nwidget,product,planned:T-FIX-01 owner:smithers-8a\nunused,product,planned:T-FIX-01 owner:smithers-8a\n")
    const before = snapshot(dir)
    const badEnv = failure === "wrong sqlc" ? { ...env, PATH: "/usr/bin:/bin" } : env
    const result = command(dir, process.execPath, [script, path], badEnv)
    recordEvidence(`${vcs}-refusal-${failure}`,{before,after:snapshot(dir),result})
    assert.notEqual(result.status, 0, result.stdout + result.stderr)
    if (failure === "other reservation") assert.match(result.stdout + result.stderr, /reserved for T-FIX-01/)
    assert.deepEqual(snapshot(dir), before)
   } finally {rmSync(dir, { recursive: true, force: true })}
  })
 }
