// Simulate the kernel UID observation in a child process; no privileged process
// or credentials are needed to prove refusal precedes repository/tool access.
test("C-PRC-02/generator-uid-before-repository-use", () => {
 const dir = mkdtempSync(join(tmpdir(), "renumber-uid-"))
 try {
  schemaFixture(dir); checkout(dir,"git"); pending(dir)
  const preload=join(dir,"uid.mjs")
  writeFileSync(preload,"process.getuid = () => 0;\n")
  const before=snapshot(dir)
  const result=command(dir,process.execPath,["--import",preload,script,"does-not-exist.sql"],env)
  recordEvidence("generator-uid-before-repository-use",{before,after:snapshot(dir),result})
  assert.notEqual(result.status,0)
  assert.match(result.stderr,/must run as an unprivileged machine user/)
  assert.deepEqual(snapshot(dir),before)
 } finally {rmSync(dir,{recursive:true,force:true})}
})

