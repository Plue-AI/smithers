import * as Fs from "node:fs/promises"
import * as Os from "node:os"
import * as Path from "node:path"
import { afterEach, describe, expect, it } from "vitest"
import { serve } from "./helpers/ServeCli.ts"

type Kind = "text" | "symlink"

const original = "external bytes must survive\n"
const generated = "generated bytes\n"
const roots: Array<string> = []

afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => Fs.rm(root, { recursive: true, force: true })))
})

const workspace = `import { Smithers as S } from "@smthrs/targets"
const packageJson = S.file("//package.json")
export const Workspace = S.Workspace("generate-emit-containment", {
  repository: "git+https://example.invalid/generate-emit-containment.git",
  cache: S.Cache({ directory: ".flows" }),
  runtime: S.Runtime.Node({ version: ">=26.4.0" }),
  packageManager: S.PackageManager.Pnpm({ manifest: packageJson, lockfile: S.file("//pnpm-lock.yaml") }),
  nodeModules: S.Npm.NodeModules({ packageJson })
})
`

const fixture = async (kind: Kind, output: string) => {
  const sandbox = await Fs.realpath(await Fs.mkdtemp(Path.join(Os.tmpdir(), "smthrs-emit-containment-")))
  roots.push(sandbox)
  const root = Path.join(sandbox, "workspace")
  const packageRoot = Path.join(root, "data")
  const external = Path.join(sandbox, "external")
  await Fs.mkdir(packageRoot, { recursive: true })
  await Fs.mkdir(external)
  await Fs.writeFile(Path.join(root, "WORKSPACE.ts"), workspace)
  await Fs.writeFile(
    Path.join(packageRoot, "PACKAGE.ts"),
    `import { Smithers as S } from "@smthrs/targets"
export const Package = S.Package({ targets: {
  artifact: S.Generate({ emit: { ${JSON.stringify(output)}: ${
      kind === "text" ? JSON.stringify(generated) : "S.symlink(\"source.txt\")"
    } } })
} })
`
  )
  await Fs.writeFile(
    Path.join(root, "package.json"),
    JSON.stringify({ name: "generate-emit-containment", private: true, packageManager: "pnpm@11.25.0" })
  )
  await Fs.writeFile(Path.join(root, "pnpm-lock.yaml"), "lockfileVersion: '9.0'\n")
  await Fs.writeFile(Path.join(packageRoot, "source.txt"), "source bytes\n")
  return { root, packageRoot, external }
}

const assertGenerated = async (kind: Kind, path: string): Promise<void> => {
  if (kind === "text") {
    expect(await Fs.readFile(path, "utf8")).toBe(generated)
  } else {
    expect((await Fs.lstat(path)).isSymbolicLink()).toBe(true)
    expect(await Fs.readlink(path)).toBe("source.txt")
  }
}

describe.each<Kind>(["text", "symlink"])("Generate.emit %s containment", (kind) => {
  it("writes an ordinary nested output and checks its declared content", async () => {
    const { root, packageRoot } = await fixture(kind, "out/nested/artifact.txt")
    const path = Path.join(packageRoot, "out/nested/artifact.txt")

    const missing = await serve(root, ["//data:artifact"])
    expect(missing.exitCode, missing.logs).toBe(1)
    expect(missing.logs).toContain("drift in declared emit outputs")
    const written = await serve(root, ["//data:artifact", "--write"])
    expect(written.exitCode, written.logs).toBe(0)
    await assertGenerated(kind, path)
    const checked = await serve(root, ["//data:artifact"])
    expect(checked.exitCode, checked.logs).toBe(0)
  })

  it("preserves an existing external destination through a symlinked parent on write", async () => {
    const { root, packageRoot, external } = await fixture(kind, "out/artifact.txt")
    const destination = Path.join(external, "artifact.txt")
    await Fs.writeFile(destination, original)
    await Fs.symlink(external, Path.join(packageRoot, "out"), "dir")

    const result = await serve(root, ["//data:artifact", "--write"])

    expect(result.exitCode, result.logs).toBe(1)
    expect(result.logs).toContain("generated output parent is a symbolic link")
    expect(await Fs.readFile(destination, "utf8")).toBe(original)
    expect((await Fs.lstat(destination)).isFile()).toBe(true)
    expect(await Fs.readdir(external)).toEqual(["artifact.txt"])
  })

  it("refuses a matching external destination through a symlinked parent on check", async () => {
    const { root, packageRoot, external } = await fixture(kind, "out/artifact.txt")
    const destination = Path.join(external, "artifact.txt")
    if (kind === "text") await Fs.writeFile(destination, generated)
    else await Fs.symlink("source.txt", destination, "file")
    await Fs.symlink(external, Path.join(packageRoot, "out"), "dir")

    const result = await serve(root, ["//data:artifact"])

    expect(result.exitCode, result.logs).toBe(1)
    expect(result.logs).toContain("generated output parent is a symbolic link")
    await assertGenerated(kind, destination)
    expect(await Fs.readdir(external)).toEqual(["artifact.txt"])
  })

  it("does not create a missing external destination through a symlinked parent", async () => {
    const { root, packageRoot, external } = await fixture(kind, "out/nested/artifact.txt")
    await Fs.symlink(external, Path.join(packageRoot, "out"), "dir")

    const written = await serve(root, ["//data:artifact", "--write"])
    expect(written.exitCode, written.logs).toBe(1)
    expect(written.logs).toContain("generated output parent is a symbolic link")
    expect(await Fs.readdir(external)).toEqual([])

    const checked = await serve(root, ["//data:artifact"])
    expect(checked.exitCode, checked.logs).toBe(1)
    expect(checked.logs).toContain("generated output parent is a symbolic link")
    expect(await Fs.readdir(external)).toEqual([])
  })
})

describe("Generate.emit text leaf symlink", () => {
  it("refuses write and check while preserving an external file", async () => {
    const { root, packageRoot, external } = await fixture("text", "out/artifact.txt")
    const destination = Path.join(external, "artifact.txt")
    const link = Path.join(packageRoot, "out/artifact.txt")
    await Fs.mkdir(Path.dirname(link))
    await Fs.writeFile(destination, generated)
    await Fs.symlink(destination, link, "file")

    const written = await serve(root, ["//data:artifact", "--write"])
    expect(written.exitCode, written.logs).toBe(1)
    expect(written.logs).toContain("generated output is a symbolic link")
    expect((await Fs.lstat(link)).isSymbolicLink()).toBe(true)
    expect(await Fs.readlink(link)).toBe(destination)
    expect(await Fs.readFile(destination, "utf8")).toBe(generated)

    const checked = await serve(root, ["//data:artifact"])
    expect(checked.exitCode, checked.logs).toBe(1)
    expect((await Fs.lstat(link)).isSymbolicLink()).toBe(true)
    expect(await Fs.readFile(destination, "utf8")).toBe(generated)
  })
})
