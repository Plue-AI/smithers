/**
 * The `node_modules` target.
 *
 * `node_modules` is not a special case of the build graph. It is a target,
 * produced by a target, keyed on declared content, and depended on by everything
 * that runs a workspace-installed tool.
 *
 * This replaces `PnpmWorkspace`, which was a manager-specific wrapper that
 * configured itself: it hardcoded pnpm, took the lockfile and workspace
 * manifest as attrs it did not use, and left the Install flow to discover the
 * manager through its own layer. One target now covers every manager, and the
 * manager arrives as the workspace's own declaration, resolved when the graph
 * is planned.
 *
 * @since 0.1.0
 */

import { Install as InstallFlow, PackageManager as PackageManagerService } from "@smthrs/build"
import * as Effect from "effect/Effect"
import * as Schema from "effect/Schema"
import * as Attr from "./Attr.ts"
import * as Input from "./Input.ts"
import * as PackageManager from "./PackageManager.ts"
import * as Target from "./Target.ts"

/**
 * Attributes for {@link Install}.
 *
 * `packageManager` is the declaration every other tool-running target also
 * takes, so one workspace value drives the install and every tool that
 * resolves out of the tree it produces. A PACKAGE.ts omits it: the planner
 * fills it from `WORKSPACE.ts`.
 *
 * `lockfile` is a target rather than a file declaration: the lockfile is
 * generated by {@link Lockfile}, and depending on the target is what orders the
 * two. The lockfile's *content* still reaches this target's key, through the
 * `inputs` function below, so a hand-edited lockfile invalidates the install
 * even though the same file is another target's output.
 *
 * @category schemas
 * @since 0.1.0
 */
export const Attrs = Schema.Struct({
  packageManager: Schema.optional(PackageManager.PackageManager),
  /**
   * The lockfile the install reads, relative to the workspace root.
   *
   * A target's declared inputs are fixed when the declaration is evaluated,
   * and the workspace declaration is not read until the graph is planned, so a
   * declaration that leaves the manager to the workspace names the file it
   * installs from instead. With a manager declared it defaults to the file
   * that manager writes.
   */
  lockfilePath: Schema.optional(Schema.NonEmptyString),
  /**
   * The target that generates the lockfile, or `null` to use a checked-in one.
   *
   * @default null
   */
  lockfile: Schema.NullOr(Target.Target).pipe(
    Schema.withConstructorDefault(Effect.succeed(null))
  ),
  /** The root manifest target, when the manifest is generated. @default null */
  manifest: Schema.NullOr(Target.Target).pipe(
    Schema.withConstructorDefault(Effect.succeed(null))
  ),
  /** The workspace-definition target, when it is generated. @default null */
  workspace: Schema.NullOr(Target.Target).pipe(
    Schema.withConstructorDefault(Effect.succeed(null))
  ),
  /** The hand-written pnpm workspace definition and the manifests it selects. @default null */
  workspaceManifest: Schema.NullOr(Input.PnpmWorkspace).pipe(
    Schema.withConstructorDefault(Effect.succeed(null))
  ),
  /** Patch files used by a pnpm workspace's patchedDependencies. */
  patches: Schema.Array(Input.File).pipe(Schema.withConstructorDefault(Effect.succeed([]))),
  /**
   * The registry hosts, and the hosts of anything the installed packages
   * fetch ahead of use (browser builds, for one), the install reaches.
   */
  destinations: Schema.optional(Attr.Destinations)
})

/**
 * Attributes for {@link Install}.
 *
 * @category models
 * @since 0.1.0
 */
export type Attrs = typeof Attrs.Type

/**
 * The files an install is keyed on, whoever produced them.
 *
 * The lockfile pins every resolved version, `.npmrc` decides which registry and
 * which credentials the manager talks to, and the root manifest decides what the
 * workspace asked for. A change in any of the three changes what an install
 * produces, so all three are declared inputs.
 *
 * @category constructors
 * @since 0.1.0
 */
export const inputsFor = (attrs: Attrs): ReadonlyArray<Input.Declared> => [
  Input.file(attrs.lockfilePath ?? PackageManager.lockfileName(attrs.packageManager)),
  Input.file(".npmrc"),
  Input.file("package.json"),
  Input.file(".pnpmfile.mjs"),
  ...attrs.patches,
  ...(attrs.workspaceManifest === null ? [] : [attrs.workspaceManifest])
]

/**
 * The refusal text for an install under the Bun package manager.
 *
 * Re-exported from `@smthrs/build` so declaration-side tooling, such as
 * workspace generation, can refuse with the same words without depending on
 * the install implementation package.
 *
 * @category constants
 * @since 1.0.0
 */
export const bunInstallUnsupportedMessage: string = PackageManagerService.bunInstallUnsupportedMessage

const definition = Target.make("Install", {
  attrs: Attrs,
  workspaceAttrs: ["packageManager"],
  kinds: ["run"],
  success: InstallFlow.LinkManifest,
  error: PackageManagerService.PackageManagerError,
  cache: false,
  inputs: inputsFor,
  implementation: (attrs) => {
    const manager = PackageManager.required(attrs.packageManager).name
    // The planner refuses a workspace-filled Bun manager before this runs;
    // this is the second lock.
    if (manager !== "pnpm") throw PackageManagerService.bunInstallUnsupported()
    return InstallFlow.Install.call({ manager })
  }
})

/**
 * Plans an install for the declared package manager.
 *
 * The wrapper target is not cacheable: a cache hit would report a link manifest
 * without restoring either the manager store or the `node_modules` tree it
 * describes. The nested flow's own steps are keyed for local freshness, which is
 * where skipping unchanged work belongs.
 *
 * Only pnpm installs. A declaration that names the Bun package manager is
 * refused here, when the target is constructed, with
 * `PackageManager.bunInstallUnsupportedMessage`; a Bun manager filled in from
 * `WORKSPACE.ts` is refused by the planner before anything spawns.
 *
 * @example
 * ```ts
 * import { Smithers } from "@smthrs/targets"
 *
 * // The manager comes from the workspace declaration; the lockfile is named
 * // here because declared inputs are fixed before any workspace is read.
 * export const nodeModules = Smithers.Install({ lockfilePath: "pnpm-lock.yaml" })
 * ```
 *
 * @category targets
 * @since 0.1.0
 */
export const Install = Object.assign(
  (attrs: Parameters<typeof definition>[0]) => {
    const manager = (attrs as { readonly packageManager?: unknown }).packageManager
    if (PackageManager.isPackageManager(manager) && manager.name === "bun") {
      throw new Error(`unsupported: ${bunInstallUnsupportedMessage}`)
    }
    return definition(attrs)
  },
  definition
)
