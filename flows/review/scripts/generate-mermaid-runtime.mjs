/** Generate a pinned renderer resource outside the executable flow closure. */
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { gzipSync } from "node:zlib"
const source = readFileSync(createRequire(import.meta.url).resolve("mermaid/dist/mermaid.min.js"))
const encoded = gzipSync(source, { level: 9 }).toString("base64")
const output = `/** Generated by scripts/generate-mermaid-runtime.mjs; runtime resource is part of the pinned flow closure. */\nconst runtime = ${JSON.stringify(encoded)};\nexport function mermaidRuntimeGzipBase64(): string { return runtime; }\n`
const path = new URL("../src/walkthrough/mermaidRuntimeGzipBase64.ts", import.meta.url)
if (process.argv.includes("--check")) {
 if (readFileSync(path, "utf8") !== output) throw new Error("Mermaid renderer resource is stale; regenerate it")
} else writeFileSync(path, output)
