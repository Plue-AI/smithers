#!/usr/bin/env node
/**
 * gen-sites.mjs
 *
 * Generates every per-package docs site under apps/docs/ from manifest.mjs:
 * package.json, astro.config.mjs, alchemy.run.ts, tsconfig.json, PACKAGE.ts,
 * src/content.config.ts, the Starlight stylesheet, and the favicon and logo
 * assets. The generator is the source of truth for all of it: edit this file
 * (or shared/starlight.css, shared/assets/), rerun it, and `--check` guards
 * the drift under lint, the same contract as apps/site's sync scripts.
 *
 * src/content/docs/ is NOT generated here; sync-content.mjs owns that tree.
 * Nor is security.ts: each site's SecurityReview options are hand-authored
 * there, and the generated PACKAGE.ts imports them. A site without one fails.
 *
 * Usage: node apps/docs/shared/gen-sites.mjs [--check]
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { docsRoot, sites } from "./manifest.mjs"

const checkMode = process.argv.includes("--check")
const sharedRoot = dirname(fileURLToPath(import.meta.url))

const header = (path) => `Generated by apps/docs/shared/gen-sites.mjs from apps/docs/shared/manifest.mjs. Edit the generator, then rerun it: node apps/docs/shared/gen-sites.mjs`

/** The package.json of one site: scripts mirror apps/site, versions pinned to its ranges. */
const packageJson = (site) =>
  `${JSON.stringify(
    {
      name: `@smithers/docs-${site.slug}`,
      version: "0.0.1",
      private: true,
      description: `The ${site.name} documentation site (${site.domain})`,
      type: "module",
      scripts: {
        dev: "astro dev",
        build: "astro build",
        check: "astro check",
        preview: "astro preview",
        "sync:docs": `node ../shared/sync-content.mjs ${site.slug}`,
        "check:docs": `node ../shared/sync-content.mjs ${site.slug} --check`,
        plan: "alchemy deploy --dry-run --stage prod",
        deploy: "alchemy deploy --stage prod",
        destroy: "alchemy destroy --stage prod"
      },
      devDependencies: {
        "@astrojs/check": "^0.9.10",
        "@smithers/docs-shared": "workspace:*",
        alchemy: "2.0.0-beta.76",
        typescript: "~5.9.3"
      },
      dependencies: {
        "@astrojs/starlight": "^0.42.0",
        astro: "^7.3.1"
      }
    },
    null,
    2
  )}\n`

/** The astro config: starlight imported here (never through the shared
 * package: astro's config loader only compiles starlight's raw .ts entry
 * when the import comes from the config file), the rest from the factory. */
const astroConfig = (site) => `// @ts-check
// ${header("astro.config.mjs")}
import { fileURLToPath } from "node:url"
import starlight from "@astrojs/starlight"
import { defineDocsSite } from "@smithers/docs-shared/starlight"

export default defineDocsSite({
  starlight,
  slug: ${JSON.stringify(site.slug)},
  title: ${JSON.stringify(site.title)},
  description: ${JSON.stringify(site.description)},
  sourceDir: ${JSON.stringify(site.dir)},
  contentDir: fileURLToPath(new URL("./src/content/docs", import.meta.url))
})
`

/** The Alchemy deploy: one call into the shared factory. */
const alchemyRun = (site) => `/**
 * Alchemy infrastructure-as-code for ${site.domain}, the ${site.name} docs site.
 * ${header("alchemy.run.ts")}
 *
 * Plan:     pnpm -C apps/docs/${site.slug} run plan
 * Deploy:   pnpm -C apps/docs/${site.slug} run deploy
 * Destroy:  pnpm -C apps/docs/${site.slug} run destroy
 * Stage prod; state lives in the account's alchemy-state-store. The first
 * Alchemy 2 plan and deploy of a live site add \`--adopt\`. See apps/docs/README.md.
 */
import { makeDocsSiteStack } from "@smithers/docs-shared/alchemy-site"

export default makeDocsSiteStack({ slug: ${JSON.stringify(site.slug)} })
`

/** The package tsconfig: apps/site's, verbatim. */
const tsconfig = () =>
  `${JSON.stringify(
    {
      extends: "astro/tsconfigs/strict",
      include: [".astro/types.d.ts", "**/*"],
      exclude: ["dist"]
    },
    null,
    2
  )}\n`

/** camelCase identifier for the source package's PACKAGE.ts import binding. */
const bindingFor = (slug) => `${slug.replace(/-([a-z])/g, (_m, c) => c.toUpperCase())}Package`

/** The smthrs targets: astro check, astro build, and the drift-checked content sync. */
const packageTs = (site) => `/**
 * Targets for ${site.domain}, the ${site.name} documentation site.
 * ${header("PACKAGE.ts")}
 *
 * The content edge is the source package's docsFiles filegroup, imported by
 * label: input globs are package scoped, so a glob declared here could never
 * reach ${site.dir}. The kit edge is apps/docs/shared's sources group:
 * astro.config.mjs imports its config factory, which mounts its release
 * notice middleware, so the rendered HTML changes when the kit does.
 */
import { Smithers } from "@smthrs/targets"
import { Package as ${bindingFor(site.slug)} } from "../../../${site.dir}/PACKAGE.ts"
import { Package as docsSharedPackage } from "../shared/PACKAGE.ts"
import { security } from "./security.ts"

const cwd = "apps/docs/${site.slug}"

/** The site's config, content, styles, scripts, public assets, and tsconfig. */
const sources = [
  Smithers.glob("//apps/docs/${site.slug}/src/**/*"),
  Smithers.glob("//apps/docs/${site.slug}/public/**/*"),
  Smithers.file("//apps/docs/${site.slug}/astro.config.mjs"),
  Smithers.file("//apps/docs/${site.slug}/package.json"),
  Smithers.file("//apps/docs/${site.slug}/tsconfig.json")
]

/** The shared Starlight kit the config imports; a filegroup is an edge, and its digest reaches this package's keys. */
const kit = docsSharedPackage.sources

/** \`astro check\`: the site typechecks against its package tsconfig. */
const check = Smithers.ToolRun({
  command: "pnpm",
  args: ["run", "check"],
  inputs: sources,
  deps: [kit],
  cwd
})

/** \`astro build\`: the static site into \`apps/docs/${site.slug}/dist\`. */
const build = Smithers.ToolBuild({
  tool: "astro",
  command: "pnpm",
  args: ["run", "build"],
  inputs: sources,
  outputs: ["dist"],
  deps: [kit],
  env: {},
  cache: true,
  cwd
})

/**
 * The committed content tree, stitched from ${site.name}'s colocated docs by
 * apps/docs/shared/sync-content.mjs. The committed copy is the cache:
 * \`smithers-build lint //apps/docs/${site.slug}:contentSync\` fails on drift,
 * \`smithers-build run //apps/docs/${site.slug}:contentSync\` applies.
 */
const contentSync = Smithers.Generate({
  summary: ${JSON.stringify(`Sync ${site.name}'s colocated docs into the site content tree; check drift under lint.`)},
  script: Smithers.file("//apps/docs/shared/sync-content.mjs"),
  env: { SMITHERS_DOCS_SLUG: ${JSON.stringify(site.slug)} },
  data: [${bindingFor(site.slug)}.docsFiles],
  changes: ["src/content/docs/**"]
})

/**
 * Security review of the site. The checks are hand-authored in ./security.ts;
 * \`security\` reviews the diff against origin/main, \`securityAudit\` audits
 * every included file.
 */
const securityReview = Smithers.SecurityReview({ cwd, ...security })

export const Package = Smithers.Package({
  targets: { check, build, contentSync, ...securityReview }
})
`

/** The Starlight content collection registration, apps/site's verbatim. */
const contentConfig = () => `import { docsLoader } from "@astrojs/starlight/loaders"
import { docsSchema } from "@astrojs/starlight/schema"
import { defineCollection } from "astro:content"

export const collections = {
  docs: defineCollection({ loader: docsLoader(), schema: docsSchema() })
}
`

/** The generated files of one site: relative path -> string or Buffer. */
const filesFor = (site) => {
  const files = new Map()
  files.set(".gitignore", "dist\n.astro\n")
  files.set("package.json", packageJson(site))
  files.set("astro.config.mjs", astroConfig(site))
  files.set("alchemy.run.ts", alchemyRun(site))
  files.set("tsconfig.json", tsconfig())
  files.set("PACKAGE.ts", packageTs(site))
  files.set("src/content.config.ts", contentConfig())
  files.set("src/styles/starlight.css", readFileSync(join(sharedRoot, "starlight.css")))
  files.set("src/docs-assets/logo.png", readFileSync(join(sharedRoot, "assets/logo.png")))
  files.set("public/favicon.png", readFileSync(join(sharedRoot, "assets/favicon.png")))
  return files
}

const bytesEqual = (a, b) => Buffer.compare(Buffer.isBuffer(a) ? a : Buffer.from(a), Buffer.isBuffer(b) ? b : Buffer.from(b)) === 0

let drift = 0
let missing = 0
for (const site of sites) {
  if (!existsSync(join(site.siteDir, "security.ts"))) {
    console.error(`missing: apps/docs/${site.slug}/security.ts (hand-authored SecurityReview options the generated PACKAGE.ts imports)`)
    missing++
  }
  for (const [rel, content] of filesFor(site)) {
    const abs = join(site.siteDir, rel)
    if (checkMode) {
      if (!existsSync(abs) || !bytesEqual(readFileSync(abs), content)) {
        console.error(`drift: apps/docs/${site.slug}/${rel}`)
        drift++
      }
    } else {
      if (existsSync(abs) && bytesEqual(readFileSync(abs), content)) continue
      mkdirSync(dirname(abs), { recursive: true })
      writeFileSync(abs, content)
    }
  }
}

// A site directory the manifest does not know would deploy nothing but would
// still join the workspace: report it rather than let it rot.
const known = new Set(sites.map((site) => site.slug))
for (const entry of readdirSync(docsRoot, { withFileTypes: true })) {
  if (entry.isDirectory() && entry.name !== "shared" && !known.has(entry.name)) {
    if (checkMode) {
      console.error(`unknown site directory: apps/docs/${entry.name} (not in manifest.mjs)`)
      drift++
    } else {
      console.log(`note: apps/docs/${entry.name} is not in manifest.mjs; left alone`)
    }
  }
}

if (missing > 0) {
  console.error(`gen-sites: ${missing} site(s) lack security.ts; write their checks, then rerun`)
  process.exit(1)
}
if (checkMode) {
  if (drift > 0) {
    console.error(`gen-sites: ${drift} file(s) out of date; run node apps/docs/shared/gen-sites.mjs`)
    process.exit(1)
  }
  console.log(`gen-sites: ${sites.length} sites clean`)
} else {
  console.log(`gen-sites: wrote ${sites.length} sites`)
}
