/**
 * Projects the RC support reference and its entry pages from colocated docs.
 * Check mode compares bytes so a site edit cannot diverge from its source.
 *
 * @since 1.0.0
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"

const site = resolve(import.meta.dirname, "..")
const check = process.argv.includes("--check")
const pages = [
  ["installation.mdx", "docs/installation.mdx"],
  ["reference/api/index.mdx", "docs/reference/api/index.mdx"],
  ["changelogs/1.0.0-rc.0.mdx", "changelogs/1.0.0-rc.0.mdx"]
]

for (const [source, destination] of pages) {
  const sourcePath = `apps/site/docs/${source}`
  const body = readFileSync(resolve(site, "docs", source), "utf8")
  const content = body.replace(
    /^---\n/,
    [
      "---",
      `# GENERATED by apps/site/scripts/sync-support-docs.mjs. Edit ${sourcePath}.`,
      `editUrl: https://github.com/smithersai/smithers/edit/main/${sourcePath}`,
      ""
    ].join("\n")
  )
  const path = resolve(site, "src/content/docs", destination)
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
      console.error(`support docs drift: ${destination}`)
      process.exitCode = 1
    }
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, content)
  }
}
if (!process.exitCode) console.log(`support docs: ${pages.length} pages ${check ? "checked" : "written"}`)
