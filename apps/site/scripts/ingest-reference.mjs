#!/usr/bin/env node
/**
 * Copies colocated reference pages into the Starlight tree.
 *
 * Each documented package writes its reference pages under
 * `<package>/docs/reference/<slug>.md` (an `Agent.Diff` target named
 * `referenceDocs` in that package's PACKAGE.ts writes them; the committed
 * file is the cache). This script is the deterministic half: it reads every
 * colocated page listed in `sources` below, keeps its frontmatter, adds the
 * Starlight fields (`editUrl`, `sidebar.order`), prefixes a generated-file
 * banner, and writes
 * `apps/site/src/content/docs/docs/reference/<area>/<slug>.mdx`. It also
 * writes one `index.mdx` per area that lists the pages, so the area route
 * exists without a hand-kept list.
 *
 * `//apps/site:referenceIngest` runs it as a `Generate` script target:
 * `smithers-build lint //apps/site:referenceIngest` fails on drift and
 * `smithers-build target //apps/site:referenceIngest --write` applies.
 *
 * Pass `--check` to report drift without writing. Reads nothing outside the listed
 * packages; the PACKAGE.ts declares the same packages' `referencePages`
 * filegroups as `data`, which is what makes the target's key move when a
 * colocated page changes.
 */
import { mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises"
import { dirname, join, posix, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { sites } from "../../docs/shared/manifest.mjs"
import { outputRelFor, routeFor } from "../../docs/shared/sync-content.mjs"

/** Source package directory to docs-site slug, for cross-site link rewrites. */
const slugByPackageDir = new Map(sites.map((site) => [site.dir, site.slug]))

const check = process.argv.includes("--check")
const here = dirname(fileURLToPath(import.meta.url))
const site = resolve(here, "..")
const root = resolve(site, "..", "..")
const outRoot = join(site, "src", "content", "docs", "docs", "reference")

/**
 * The packages whose `docs/reference/*.md` pages are ingested.
 */
const sources = [
  { package: "packages/smithers/flows/flow" },
  { package: "packages/smithers/flows/engine" },
  { package: "packages/smithers/build/targets" }
]

/** The areas this script owns under `reference/`, in sidebar order. */
const areas = {
  api: {
    title: "API",
    description: "One page per published @smthrs package: what it exports, with the types and defaults from source.",
    order: 20
  },
  targets: {
    title: "Targets",
    description: "One page per @smthrs/targets rule: attributes, verbs, cache behavior, and channels from Target.make.",
    order: 30
  }
}

const editBase = "https://github.com/smithersai/smithers/edit/main/"
const regenerate = "pnpm exec smithers-build target //apps/site:referenceIngest --write"

/**
 * The line every file this script writes carries in its frontmatter. Only a
 * file carrying it is ever overwritten or removed: `reference/api/` is shared
 * with `sync-api-docs.mjs`, which projects each package's `docs/api.md`, and
 * a hand-authored page may sit beside either. A colocated page whose slug is
 * taken by a foreign file is reported and skipped, never written over.
 */
const owner = "# GENERATED by apps/site/scripts/ingest-reference.mjs. Do not edit;"

/** Parses a leading YAML frontmatter block of `key: value` lines. */
const parseFrontmatter = (text, path) => {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text)
  if (match === null) throw new Error(`${path}: a colocated reference page starts with frontmatter`)
  const fields = {}
  for (const line of match[1].split(/\r?\n/)) {
    // Nested keys (`sidebar:` then `  order: 1`) are read by the index
    // builder's own regex; the flat parser skips indented lines.
    if (line.trim() === "" || line.trimStart().startsWith("#") || /^\s/.test(line)) continue
    const colon = line.indexOf(":")
    if (colon === -1) throw new Error(`${path}: frontmatter line is not key: value: ${line}`)
    const key = line.slice(0, colon).trim()
    let value = line.slice(colon + 1).trim()
    if (/^".*"$/.test(value)) value = JSON.parse(value)
    else if (/^'.*'$/.test(value)) value = value.slice(1, -1).replace(/''/g, "'")
    fields[key] = value
  }
  return { fields, body: text.slice(match[0].length) }
}

const yamlString = (value) => JSON.stringify(String(value))

const required = (fields, key, path) => {
  const value = fields[key]
  if (typeof value !== "string" || value.trim() === "") throw new Error(`${path}: frontmatter needs ${key}`)
  return value
}

/** Reads one colocated page into its emitted form. */
const readPage = async (pkg, file) => {
  const sourcePath = posix.join(pkg, "docs", "reference", file)
  const text = await readFile(join(root, sourcePath), "utf8")
  const { fields, body } = parseFrontmatter(text, sourcePath)
  const area = required(fields, "area", sourcePath)
  if (!(area in areas)) throw new Error(`${sourcePath}: unknown area ${area}; one of ${Object.keys(areas).join(", ")}`)
  const slug = fields.slug ?? file.replace(/\.md$/, "")
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) throw new Error(`${sourcePath}: slug must be lowercase kebab-case: ${slug}`)
  const order = Number(fields.order ?? 100)
  if (!Number.isInteger(order)) throw new Error(`${sourcePath}: order must be an integer`)
  if (/^#\s/m.test(body)) throw new Error(`${sourcePath}: no H1 in the body; the title renders it`)
  if (/[–—]/.test(body) || /[–—]/.test(text.slice(0, text.length - body.length))) {
    throw new Error(`${sourcePath}: no em-dash or en-dash in prose`)
  }
  return {
    area,
    slug,
    order,
    sourcePath,
    title: required(fields, "title", sourcePath),
    description: required(fields, "description", sourcePath),
    body: rewriteCrossPackageLinks(toMdx(body), sourcePath).replace(/\s+$/, "") + "\n"
  }
}

// Markdown to MDX: MDX has no HTML comments, so a colocated page's
// `<!-- verify: ... -->` notes become JSX comment expressions. Fenced code is
// left alone so a verbatim sample keeps its bytes.
const toMdx = (body) => {
  const parts = body.split(/(^```[\s\S]*?^```[ \t]*$)/m)
  return parts
    .map((part, index) => (index % 2 === 1 ? part : part.replace(/<!--([\s\S]*?)-->/g, (_, text) => `{/*${text.replace(/\*\//g, "* /")}*/}`)))
    .join("")
}

/**
 * Rewrites the cross-package link forms a colocated page is written in.
 *
 * A colocated page uses `/api/<slug>` because that is the contract the
 * per-package sites are authored against (apps/docs/shared/AUTHORING.md).
 * smithers.sh has no `/api/` route, so copying one here verbatim publishes a
 * dead link: `check-docs.mjs` calls it "link to nowhere". The aggregate
 * reference lives under `/docs/reference/api/<slug>/`, so that is where the
 * link resolves on this site. `sync-api-docs.mjs` performs the same rewrite
 * for `docs/api.md`; this script owns the pages that one skips, and the two
 * have to agree or a page's links depend on which generator wrote it.
 */
const rewriteCrossPackageLinks = (body, sourcePath) =>
  body
    .replace(
      /\]\((?:https:\/\/smithers\.sh)?\/api\/([a-z0-9-]+)\/?(#[^)]+)?\)/gi,
      (_m, slug, frag) => `](/docs/reference/api/${slug.toLowerCase()}/${frag ?? ""})`
    )
    .replace(/\]\((?:https:\/\/smithers\.sh)?\/api\/?\)/gi, "](/docs/reference/api/)")
    // A relative .md link names a sibling page of the package's own docs tree
    // (`../api.md`, `./concepts/x.md`). That page exists, but on the package's
    // site rather than here, and check-docs.mjs rejects a relative link
    // outright. Resolve it against the package's docs root and send it to that
    // site, using the same mapping sync-content.mjs applies when it builds it.
    .replace(/\]\((\.{1,2}\/[^)\s#]+\.md)(#[^)]+)?\)/g, (whole, rel, frag) => {
      const packageRoot = sourcePath.split("/docs/reference/")[0]
      const slug = slugByPackageDir.get(packageRoot)
      if (slug === undefined) return whole
      const fromDocs = posix.normalize(posix.join("reference", rel))
      if (fromDocs.startsWith("..")) return whole
      return `](https://${slug}.smithers.sh${routeFor(outputRelFor(fromDocs))}${frag ?? ""})`
    })

const renderPage = (page) => {
  const packageRoot = page.sourcePath.split("/docs/reference/")[0]
  const sourceLinks = `> **Source:** [implementation](${editBase.replace("/edit/", "/tree/")}${packageRoot}/src) · [reference source](${editBase.replace("/edit/", "/blob/")}${page.sourcePath})`
  return [
    "---",
    `${owner} edit ${page.sourcePath} and run:`,
    `#   ${regenerate}`,
    `title: ${yamlString(page.title)}`,
    `description: ${yamlString(page.description)}`,
    `editUrl: ${yamlString(editBase + page.sourcePath)}`,
    "sidebar:",
    `  order: ${page.order}`,
    "---",
    "",
    `{/* Generated from ${page.sourcePath}. Edit the source, then run \`${regenerate}\`. */}`,
    "",
    sourceLinks,
    "",
    page.body
  ].join("\n")
}

const renderIndex = (areaKey, pages) => {
  const area = areas[areaKey]
  const entries = pages
    .map((page) =>
      `| [${page.title}](/docs/reference/${areaKey}/${page.slug}/) | ${page.description.replaceAll("|", "\\|")} |`
    )
    .join("\n")
  return [
    "---",
    `${owner} the page list is read from the pages beside it. Run:`,
    `#   ${regenerate}`,
    `title: ${yamlString(area.title)}`,
    `description: ${yamlString(area.description)}`,
    `editUrl: ${yamlString(editBase + "apps/site/scripts/ingest-reference.mjs")}`,
    "sidebar:",
    "  order: 0",
    "---",
    "",
    `{/* Generated by apps/site/scripts/ingest-reference.mjs. Run \`${regenerate}\`. */}`,
    "",
    "Choose a reference by package or rule. Each page links to its implementation and editable source.",
    "",
    "| Reference | Purpose |",
    "| --- | --- |",
    entries,
    ""
  ].join("\n")
}

const exists = async (path) => {
  try {
    await stat(path)
    return true
  } catch {
    return false
  }
}

const isOwned = async (path) => (await exists(path)) && (await readFile(path, "utf8")).includes(owner)

/** Title, description, and order of any page in an area directory, this script's or not. */
const indexEntry = async (directory, file) => {
  const text = await readFile(join(directory, file), "utf8")
  const { fields } = parseFrontmatter(text, file)
  const sidebar = /^sidebar:\s*\n\s+order:\s*(-?\d+)/m.exec(text)
  return {
    slug: file.replace(/\.mdx$/, ""),
    title: fields.title ?? file,
    description: fields.description ?? "",
    order: sidebar === null ? Number(fields.order ?? 100) : Number(sidebar[1])
  }
}

const main = async () => {
  const pages = []
  for (const source of sources) {
    const directory = join(root, source.package, "docs", "reference")
    if (!(await exists(directory))) continue
    const files = (await readdir(directory)).filter((file) => file.endsWith(".md")).sort()
    for (const file of files) pages.push(await readPage(source.package, file))
  }

  const byArea = new Map(Object.keys(areas).map((area) => [area, []]))
  for (const page of pages) {
    const list = byArea.get(page.area)
    if (list.some((other) => other.slug === page.slug)) {
      throw new Error(`duplicate slug ${page.area}/${page.slug} from ${page.sourcePath}`)
    }
    list.push(page)
  }

  let written = 0
  const skipped = []
  const drifted = []
  for (const [area, list] of byArea) {
    const directory = join(outRoot, area)
    if (!check) await mkdir(directory, { recursive: true })
    // Remove only this script's own stale outputs.
    const keep = new Set(["index.mdx", ...list.map((page) => `${page.slug}.mdx`)])
    for (const entry of await readdir(directory)) {
      const path = join(directory, entry)
      if (!keep.has(entry) && (await isOwned(path))) {
        if (!check) await rm(path)
        written += 1
      }
    }
    const outputs = []
    for (const page of list) {
      const target = join(directory, `${page.slug}.mdx`)
      if ((await exists(target)) && !(await isOwned(target))) {
        skipped.push(`${page.sourcePath} -> reference/${area}/${page.slug}.mdx exists and is not this script's`)
        continue
      }
      outputs.push([`${page.slug}.mdx`, renderPage(page)])
    }
    for (const [name, content] of outputs) {
      const target = join(directory, name)
      const current = (await exists(target)) ? await readFile(target, "utf8") : undefined
      if (current !== content) {
        if (!check) await writeFile(target, content, "utf8")
        else drifted.push(relative(root, target))
        written += 1
      }
    }
    // The index lists every page in the area, whichever script wrote it.
    const entries = []
    for (const file of (await readdir(directory)).sort()) {
      if (file.endsWith(".mdx") && file !== "index.mdx") entries.push(await indexEntry(directory, file))
    }
    entries.sort((a, b) => a.order - b.order || a.slug.localeCompare(b.slug))
    const index = join(directory, "index.mdx")
    if (entries.length === 0) {
      if (await isOwned(index)) {
        if (!check) await rm(index)
        else drifted.push(relative(root, index))
        written += 1
      }
      skipped.push(`reference/${area}/ has no pages yet; no index written`)
    } else if ((await exists(index)) && !(await isOwned(index))) {
      skipped.push(`reference/${area}/index.mdx exists and is not this script's`)
    } else {
      const content = renderIndex(area, entries)
      const current = (await exists(index)) ? await readFile(index, "utf8") : undefined
      if (current !== content) {
        if (!check) await writeFile(index, content, "utf8")
        else drifted.push(relative(root, index))
        written += 1
      }
    }
  }
  for (const line of skipped) process.stderr.write(`ingest-reference: skipped ${line}\n`)
  for (const path of drifted) process.stderr.write(`drift: ${path}\n`)
  process.stdout.write(`ingest-reference: ${pages.length} page(s), ${written} file(s) ${check ? "with drift" : "written"}, ${skipped.length} skipped\n`)
  if (check && written > 0) {
    process.stderr.write("ingest-reference: run node apps/site/scripts/ingest-reference.mjs\n")
    process.exitCode = 1
  }
}

main().catch((error) => {
  process.stderr.write(`ingest-reference: ${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
})
