/** Check public page selection while preserving the complete CLI data contract. */
import assert from "node:assert/strict"
import { spawnSync } from "node:child_process"
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import test from "node:test"

const retired = ["admin", "artifact", "cache", "egress", "label", "notification", "org", "stack", "triggers", "tui", "variable", "webhook"]
const owner = "# GENERATED by apps/site/scripts/gen-cli-data.mjs from --help. Do not edit."

function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), "smithers-cli-docs-"))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  const write = (path, contents) => {
    mkdirSync(dirname(join(root, path)), { recursive: true })
    writeFileSync(join(root, path), contents)
  }
  write("package.json", '{"type":"module"}')
  write("packages/smithers/package.json", JSON.stringify({ version: "1.2.3", dependencies: { effect: "4.0.0" }, engines: { node: ">=26.4.0" } }))
  write("packages/smithers/build/build-cli/src/effect-resolution.js", "export const installEffectResolution = () => {}\n")
  // The generator consumes manifest/help data, not CLI execution. A controlled
  // data source covers selection boundaries without starting the CLI services.
  const commands = [...retired.flatMap((name) => [{ name }, { name: `${name} inspect` }]), { name: "flow" }, { name: "flow list" }, { name: "index" }, { name: "manual" }, { name: "triggers-extra" }]
  write("packages/smithers/src/Cli.ts", `
const manifest = ${JSON.stringify({ commands })}
export const makeCli = () => ({
  async serve(args, io) {
    io.stdout(args.includes("--llms-full") ? JSON.stringify(manifest) :
      "smthrs " + args.filter(arg => arg !== "--help").join(" ") + " — Canonical help.\\nUsage: smthrs\\n")
    io.exit(0)
  }
})
`)
  write("packages/smithers/src/Unsupported.ts", 'export const removedVerbs = []; export const removedFlags = []; export const migrationUrl = "https://smithers.sh/migration/1.0"\n')
  write("apps/site/src/data/migration-paths.json", '{"paths":{"flows":"Use a flow."},"flagGroups":{}}')
  write("apps/site/src/data/help/stale.txt", "Retired help capture.\n")
  write("apps/site/src/content/docs/docs/reference/cli/index.mdx", "---\ntitle: CLI\ndescription: Reference\n---\n\n| Command | Purpose |\n| --- | --- |\n| old | old |\n\nRetained index prose.\n")
  write("apps/site/src/content/docs/docs/reference/cli/manual.mdx", "Hand-written command reference.\n")
  for (const name of retired) write(`apps/site/src/content/docs/docs/reference/cli/${name}.mdx`, `---\n${owner}\n---\nOld generated page.\n`)
  const script = "apps/site/scripts/gen-cli-data.mjs"
  mkdirSync(dirname(join(root, script)), { recursive: true })
  cpSync(new URL("./gen-cli-data.mjs", import.meta.url), join(root, script))
  return {
    root,
    commands,
    read: (path) => readFileSync(join(root, path), "utf8"),
    run: (...args) => spawnSync(process.execPath, [join(root, script), ...args], { encoding: "utf8" })
  }
}

test("CLI docs omit deferred pages while retaining every command and help capture", (t) => {
  const { root, commands, read, run } = fixture(t)
  const generated = run()
  assert.equal(generated.status, 0, generated.stdout + generated.stderr)
  assert.deepEqual(JSON.parse(read("apps/site/src/data/cli-commands.json")).commands, commands)
  const index = read("apps/site/src/content/docs/docs/reference/cli/index.mdx")
  for (const name of retired) {
    assert.equal(existsSync(join(root, `apps/site/src/content/docs/docs/reference/cli/${name}.mdx`)), false, `${name}: no public page`)
    assert.ok(!index.includes(`/docs/reference/cli/${name}/`), `${name}: no dead index link`)
    for (const path of [`${name}.txt`, `${name}/inspect.txt`]) {
      assert.match(read(`apps/site/src/data/help/${path}`), /Canonical help/, `${path}: full help retained`)
    }
  }
  assert.match(index, /\/docs\/reference\/cli\/flow\//)
  assert.match(index, /\/docs\/reference\/cli\/index-command\//)
  assert.match(index, /\/docs\/reference\/cli\/triggers-extra\//, "retained prefix neighbor is not excluded")
  assert.match(index, /Retained index prose/)
  assert.match(read("apps/site/src/content/docs/docs/reference/cli/flow.mdx"), /## flow list/)
  assert.equal(read("apps/site/src/content/docs/docs/reference/cli/manual.mdx"), "Hand-written command reference.\n")
  assert.equal(existsSync(join(root, "apps/site/src/data/help/stale.txt")), false)
  const checked = run("--check")
  assert.equal(checked.status, 0, checked.stdout + checked.stderr)
})

test("CLI check reports retired owned pages and leaves them for write mode", (t) => {
  const { root, read, run } = fixture(t)
  const checked = run("--check")
  assert.equal(checked.status, 1, checked.stdout + checked.stderr)
  for (const name of retired) {
    assert.ok(checked.stderr.includes(`reference/cli/${name}.mdx is stale`), `${name}: drift receipt`)
    assert.match(read(`apps/site/src/content/docs/docs/reference/cli/${name}.mdx`), /Old generated page/)
  }
  assert.equal(existsSync(join(root, "apps/site/src/data/cli-commands.json")), false, "check mode creates no output")
  assert.equal(read("apps/site/src/data/help/stale.txt"), "Retired help capture.\n")
})
