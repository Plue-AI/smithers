/*
 * Every flow name the app declares, as a type.
 *
 * The card seam used to take `(name: string, args?: string)`, so
 * `"targets.select"` compiled exactly as readily as `"target.select"` and the
 * mistake only surfaced as a button that did nothing. The names are literals
 * in the entries modules and nowhere else, so this module lists them once and
 * derives the union; FlowName.test.ts holds the list and the registry to each
 * other, in both directions, by reading the entries modules as text.
 *
 * A flow declared at RUNTIME (a repository's flow leaf, entries/flow.ts) is
 * not here: its name arrives with a projection. A caller holding such a name
 * has a plain string and dispatches it as one.
 */

