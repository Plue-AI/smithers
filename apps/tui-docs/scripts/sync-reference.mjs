/**
 * Keep the complete command and key inventories tied to the actual TUI
 * registries. The pages are published on smithers.sh under /docs/tui/.
 */
import { writeFileSync } from "node:fs"
import { commands } from "../../tui/src/editor.ts"
import { registry } from "../../tui/src/keys.ts"
const target = new URL("../../site/src/content/docs/docs/tui/", import.meta.url)
const front = (title, description, order) =>
  `---\ntitle: "${title}"\ndescription: "${description}"\nsidebar:\n  order: ${order}\n---\n\n{/* Generated by apps/tui-docs/scripts/sync-reference.mjs from the TUI registries. Do not edit. */}\n\n`
const chat = "/docs/learn/chat/"
const guides = {
  model: "/docs/learn/models/",
  new: chat,
  resume: chat,
  conversation: chat,
  compact: chat,
  name: chat,
  copy: chat,
  summary: "/docs/learn/review-a-change/",
  chat: "/docs/tui/views/",
  filter: "/docs/tui/views/",
  grep: "/docs/tui/views/",
  smithers: "/docs/learn/issue-to-main/",
  todo: "/docs/learn/issue-to-main/#file-a-todo",
  retry: "/docs/learn/issue-to-main/",
  devtools: "/docs/learn/devtools/",
  flows: "/docs/learn/run-a-flow/",
  flow: "/docs/learn/run-a-flow/",
  quit: "/docs/tui/cli/"
}
for (const c of commands) if (!guides[c.name]) throw new Error(`No guide page for /${c.name}`)
const inventory = commands.map((c) =>
  `| \`/${c.name}${c.args ? " " + c.args.replaceAll("|", "\\|") : ""}\` | ${c.description}. | [Guide](${
    guides[c.name]
  }) |`
).join("\n")
writeFileSync(
  new URL("commands.mdx", target),
  front("Commands", "Every built-in TUI slash command.", 2) +
    `Type \`/\` to browse commands. Up/Down choose, Tab completes, Enter runs, Esc closes.\n\n| Command | Action | Details |\n| --- | --- | --- |\n${inventory}\n| \`/exit\` | Alias for \`/quit\`. | [Guide](/docs/tui/cli/) |\n\nRepository flows also appear in the menu. \`/model\` and \`/flow\` complete their arguments. An unknown command stays in the editor and names the nearest one. Stop, resume, steer, undo, custom views, and Claude Code or Codex workers are in Ctrl+K search. Start a line with \`!\` to run a shell command and add its output to the conversation, or \`!!\` to keep it out.\n`
)
let keyDoc = front("Keys", "Every TUI shortcut, grouped by where it works.", 3) +
  `Press **?** with an empty editor to see the keys for where you are. **Esc** or **?** closes the list.\n\n`
for (const context of [...new Set(registry.map((k) => k.context))]) {
  keyDoc += `## ${context[0].toUpperCase() + context.slice(1)}\n\n| Key | Action |\n| --- | --- |\n`
  for (const key of registry.filter((k) => k.context === context)) {
    keyDoc += `| ${key.keys.map((k) => "`" + k.replaceAll("|", "\\|") + "`").join(" / ")} | ${key.label}. |\n`
  }
  keyDoc += "\n"
}
keyDoc +=
  `## Editor and mouse\n\nCtrl+A/Ctrl+E move to the beginning/end of a line. Shift+Left/Right selects text in the composer, search, and text fields; typing replaces the selection. Ctrl+W deletes a word and Ctrl+U deletes to the start of the line. Ctrl+K belongs to search. Drag text to copy a selection; click tabs, worker rows, cards, or status actions to open/invoke them. Scroll with the mouse or PageUp/PageDown.\n\nCtrl+C clears the editor; twice within 500 ms exits. Ctrl+D exits only with an empty editor. Approval letters arm only after the editor is empty and their 400 ms guard has elapsed.\n\nRepository and runtime [extensions](/docs/tui/extend/) add keys under their owner in the popup. Built-in keys and text-editing bindings cannot be shadowed.\n`
writeFileSync(new URL("keys.mdx", target), keyDoc)
