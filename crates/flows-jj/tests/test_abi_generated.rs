//! Reproducible hostile parser/ABI inputs and operations confined to a TempDir.
//! Run `node scripts/run-jj-abi-campaign.mjs` to replay these exact bytes in WASM.
use std::fs;
use std::panic::{self, AssertUnwindSafe};
use std::path::Path;

use flows_jj::abi::call_json;
use flows_jj::protocol::Request;
use jj_lib::content_hash::{ContentHash, DigestUpdate, blake2b_hash};
use serde_json::{Value, json};

#[path = "support/parser_corpus.rs"]
mod corpus;
use corpus::next;

fn parameter(name: &str, fallback: u32, maximum: u32) -> u32 {
    let value =
        std::env::var(name).map_or(fallback, |text| text.parse().expect("unsigned integer"));
    assert!(value <= maximum, "{name} exceeds {maximum}");
    value
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

fn expected_diff(before: &str) -> String {
    // Hash the independently constructed complete file bytes, without the
    // content-hash serialization prefix used for structured Rust values.
    struct RawBytes<'a>(&'a [u8]);
    impl ContentHash for RawBytes<'_> {
        fn hash(&self, state: &mut impl DigestUpdate) {
            state.update(self.0);
        }
    }
    let after = format!("{before}changed\n");
    let old = hex(&blake2b_hash(&RawBytes(before.as_bytes())));
    let new = hex(&blake2b_hash(&RawBytes(after.as_bytes())));
    format!(
        "diff --git a/generated.txt b/generated.txt\nindex {}..{} 100644\n--- a/generated.txt\n+++ b/generated.txt\n@@ -1,1 +1,2 @@\n {before}+changed\n",
        &old[..10],
        &new[..10]
    )
}

fn malformed(bytes: &[u8]) -> Value {
    // The pure parser proves these generated bytes cannot dispatch filesystem ops.
    assert!(serde_json::from_slice::<Request>(bytes).is_err());
    let response: Value =
        serde_json::from_slice(&call_json(bytes)).expect("complete UTF-8 JSON response");
    assert_eq!(response.as_object().unwrap().len(), 1);
    assert_eq!(response["err"].as_object().unwrap().len(), 3);
    assert_eq!(response["err"]["code"], "unknown");
    assert_eq!(response["err"]["command"], "jj");
    assert!(
        response["err"]["message"]
            .as_str()
            .unwrap()
            .starts_with("jj: malformed request:")
    );
    response
}

fn call(value: Value) -> Value {
    serde_json::from_slice(&call_json(&serde_json::to_vec(&value).unwrap())).unwrap()
}

fn healthy(root: &Path) -> Value {
    let response = call(json!({"op":"diff","root":root,"from":"@","to":"@"}));
    assert_eq!(response, json!({"ok":{"diff":""}}));
    response
}

#[test]
fn generated_hostile_abi_campaign() {
    let seed = parameter("SMITHERS_ABI_SEED", 20_260_904, u32::MAX);
    let cases = parameter("SMITHERS_ABI_CASES", 256, 100_000);
    let steps = parameter("SMITHERS_ABI_STEPS", 4, 256);
    assert!(cases > 0 && steps > 0);
    let temp = tempfile::Builder::new()
        .prefix("flows-jj-generated-")
        .tempdir()
        .unwrap();
    let root = temp.path().join("repo");
    let artifact = std::env::var_os("SMITHERS_ABI_ARTIFACT_DIR").map(|path| {
        let directory = std::path::PathBuf::from(path);
        fs::create_dir_all(&directory).unwrap();
        directory.join("native.json")
    });
    let mut report = json!({"schemaVersion":1,"tier":"native","status":"running","seed":seed,
        "requestedCases":cases,"requestedSteps":steps,"executedCases":0,"executedSteps":0,
        "healthChecks":0,"requests":[],"operations":[]});
    let result = panic::catch_unwind(AssertUnwindSafe(|| {
        assert_eq!(call(json!({"op":"init","root":root})), json!({"ok":{}}));
        let mut state = seed;
        let boundary = [
            "-1",
            "0",
            "1",
            "2147483647",
            "2147483648",
            "4294967295",
            "4294967296",
            "9007199254740991",
            "9007199254740992",
            "18446744073709551615",
            "18446744073709551616",
            "1e400",
        ];
        for index in 0..cases {
            let bytes = match index % 10 {
                0 => vec![0xff, (next(&mut state) & 255) as u8],
                1 => {
                    let length = (next(&mut state) % 257) as usize;
                    (0..length)
                        .map(|_| (next(&mut state) >> 24) as u8)
                        .collect()
                }
                2 => format!(
                    "{{\"op\":\"status\",\"root\":{}}}",
                    boundary[(index as usize / 8) % boundary.len()]
                )
                .into_bytes(),
                3 => format!(
                    "{{\"op\":\"unknown-{}\",\"root\":\"/repo\"}}",
                    next(&mut state)
                )
                .into_bytes(),
                4 => format!(
                    "{{\"op\":\"restore\",\"root\":\"/repo\",\"changeId\":{}}}",
                    boundary[(index as usize / 8) % boundary.len()]
                )
                .into_bytes(),
                5 => [
                    b"".as_slice(),
                    b"{",
                    b"null",
                    b"[]",
                    b"{}",
                    b"{\"op\":\"diff\",\"root\":\"/repo\"}",
                    b"{\"op\":\"snapshot\",\"root\":\"/repo\",\"message\":false}",
                    b"{\"op\":\"status\",\"root\":\"\xc0\xaf\"}",
                ][(index as usize / 8) % 8]
                    .to_vec(),
                6 => format!(
                    "{{\"op\":\"workspaceAdd\",\"root\":\"/repo\",\"name\":\"lane\",\"path\":{}}}",
                    boundary[(index as usize / 8) % boundary.len()]
                )
                .into_bytes(),
                7 => {
                    let depth = 128 + (next(&mut state) % 8) as usize;
                    format!("{}0{}", "[".repeat(depth), "]".repeat(depth)).into_bytes()
                }
                _ => corpus::rejected(seed, index / 10),
            };
            report["pendingInputHex"] = json!(hex(&bytes));
            let response = malformed(&bytes);
            report["requests"]
                .as_array_mut()
                .unwrap()
                .push(json!({"index":index,"inputHex":hex(&bytes),"response":response}));
            report["executedCases"] = json!(index + 1);
            healthy(&root);
            report["healthChecks"] = json!(report["healthChecks"].as_u64().unwrap() + 1);
        }
        // Keep operation content independently replayable from seed and index.
        state = seed;
        for index in 0..steps {
            let before = format!("seed {seed} step {index} value {}\n", next(&mut state));
            fs::write(root.join("generated.txt"), &before).unwrap();
            let first =
                call(json!({"op":"snapshot","root":root,"message":format!("generated {index}")}));
            assert_eq!(first.as_object().unwrap().len(), 1);
            assert_eq!(first["ok"].as_object().unwrap().len(), 3);
            assert!(
                first["ok"]["commitId"]
                    .as_str()
                    .unwrap()
                    .bytes()
                    .all(|byte| byte.is_ascii_hexdigit())
            );
            let id = first["ok"]["commitId"].as_str().unwrap();
            assert_eq!(id.len(), 128);
            assert!(id.bytes().all(|byte| byte.is_ascii_hexdigit()));
            let change = first["ok"]["changeId"].as_str().unwrap();
            assert_eq!(change.len(), 12);
            assert!(change.bytes().all(|byte| (b'k'..=b'z').contains(&byte)));
            assert_eq!(first["ok"]["operationId"].as_str().unwrap().len(), 128);
            fs::write(root.join("generated.txt"), format!("{before}changed\n")).unwrap();
            let second = call(json!({"op":"snapshot","root":root}));
            assert_eq!(second.as_object().unwrap().len(), 1);
            assert_eq!(second["ok"].as_object().unwrap().len(), 3);
            assert!(
                second["ok"]["commitId"]
                    .as_str()
                    .unwrap()
                    .bytes()
                    .all(|byte| byte.is_ascii_hexdigit())
            );
            let other = second["ok"]["commitId"].as_str().unwrap();
            assert_eq!(other.len(), 128);
            assert!(other.bytes().all(|byte| byte.is_ascii_hexdigit()));
            assert_eq!(second["ok"]["changeId"], first["ok"]["changeId"]);
            assert_ne!(second["ok"]["operationId"], first["ok"]["operationId"]);
            assert_ne!(id, other);
            let diff = call(json!({"op":"diff","root":root,"from":id,"to":other}));
            assert_eq!(diff, json!({"ok":{"diff":expected_diff(&before)}}));
            let failure = call(json!({"op":"restore","root":root,"changeId":"kkkkkkkkkkkk"}));
            assert_eq!(
                failure,
                json!({"err":{"code":"invalid_ref","command":"jj restore --from kkkkkkkkkkkk","message":"revision \"kkkkkkkkkkkk\" doesn't exist"}})
            );
            let restore = call(json!({"op":"restore","root":root,"changeId":id}));
            assert_eq!(restore, json!({"ok":{}}));
            let restored_text = fs::read_to_string(root.join("generated.txt")).unwrap();
            assert_eq!(restored_text, before);
            let health = healthy(&root);
            // Generated backtracking through both retained snapshots checks
            // history reuse, including repeated restores to the same tree.
            let mut revisits = Vec::new();
            for turn in 0..3 {
                let target = (seed.wrapping_add(index) >> turn) & 1;
                let revision = if target == 0 { id } else { other };
                let expected = if target == 0 {
                    before.clone()
                } else {
                    format!("{before}changed\n")
                };
                let response = call(json!({"op":"restore","root":root,"changeId":revision}));
                assert_eq!(response, json!({"ok":{}}));
                let text = fs::read_to_string(root.join("generated.txt")).unwrap();
                assert_eq!(text, expected);
                let health = healthy(&root);
                revisits.push(json!({"target":target,"response":response,"restoredText":text,"health":health}));
            }
            report["operations"].as_array_mut().unwrap().push(json!({"index":index,"first":first,"second":second,"diff":diff,"failure":failure,"restore":restore,"health":health,"restoredText":restored_text,"revisits":revisits}));
            report["executedSteps"] = json!(index + 1);
        }
    }));
    report["status"] = json!(if result.is_ok() { "passed" } else { "failed" });
    if let Some(path) = artifact {
        fs::write(path, serde_json::to_vec_pretty(&report).unwrap()).unwrap();
    }
    if let Err(cause) = result {
        panic::resume_unwind(cause);
    }
    println!("ABI_CAMPAIGN_NATIVE seed={seed} cases={cases} steps={steps}");
}
